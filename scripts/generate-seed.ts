/**
 * Generates supabase/seed.sql from the curated TypeScript dataset in src/data,
 * so the database and the app can never drift apart.
 *
 *   npm run db:seed:generate
 *
 * The output is idempotent: run it as many times as you like. Apply it with the
 * service role (Supabase SQL editor, `supabase db reset`, or psql), because
 * catalogue tables are read-only to ordinary clients.
 */
import { writeFileSync } from "node:fs";
import { attire } from "../src/data/attire";
import { countries } from "../src/data/countries";
import { destinations } from "../src/data/destinations";
import { DATES_CHECKED, festivals, REGION_LABELS } from "../src/data/festivals";
import { foods } from "../src/data/foods";
import { ACTIVITY_LIBRARY } from "../src/data/matchmaker";
import { artists, playlists } from "../src/data/music";
import { brands, giftIdeas } from "../src/data/shop";

const q = (value: string | null | undefined): string => (value === null || value === undefined ? "null" : `'${value.replace(/'/g, "''")}'`);
const arr = (values: readonly string[]): string => (values.length === 0 ? "'{}'::text[]" : `array[${values.map(q).join(", ")}]::text[]`);
const json = (value: unknown): string => `${q(JSON.stringify(value))}::jsonb`;
const festivalId = (slug: string) => `(select id from public.festivals where slug = ${q(slug)})`;
const countryId = (code: string) => `(select id from public.countries where code = ${q(code)})`;
const checked = `${q(`${DATES_CHECKED}T00:00:00Z`)}::timestamptz`;

const out: string[] = [
  "-- FESTIVA seed data. GENERATED by scripts/generate-seed.ts from src/data. Do not edit by hand.",
  "begin;",
  "",
];

for (const [slug, name] of Object.entries(REGION_LABELS)) {
  out.push(`insert into public.regions (slug, name) values (${q(slug)}, ${q(name)}) on conflict (slug) do update set name = excluded.name;`);
}
out.push("");

for (const c of countries) {
  out.push(
    `insert into public.countries (code, name, region_id, blurb, languages, currency_code) values (${q(c.code)}, ${q(c.name)}, (select id from public.regions where slug = ${q(c.region)}), ${q(c.blurb)}, ${arr(c.languages)}, ${q(c.currency)}) on conflict (code) do update set name = excluded.name, region_id = excluded.region_id, blurb = excluded.blurb, languages = excluded.languages, currency_code = excluded.currency_code;`,
  );
}
out.push("");

for (const f of festivals) {
  out.push(
    `insert into public.festivals (slug, name, local_name, tagline, summary, region_id, category, observed_by, date_rule, date_note, history, significance, etiquette, genres, palette, latitude, longitude, source_url, verification_status) values (${q(f.slug)}, ${q(f.name)}, ${q(f.localName)}, ${q(f.tagline)}, ${q(f.summary)}, (select id from public.regions where slug = ${q(f.region)}), ${q(f.category)}, ${q(f.observedBy)}, ${json(f.date.kind === "table" ? { kind: "table", calendar: f.date.calendar, typicalMonths: f.date.typicalMonths } : f.date)}, ${q(f.dateNote)}, ${q(f.history)}, ${q(f.significance)}, ${arr(f.etiquette)}, ${arr(f.genres)}, ${arr(f.palette)}, ${f.lat}, ${f.lon}, ${q(f.provenance.sources[0]?.url)}, ${q(f.provenance.verification)}) on conflict (slug) do update set name = excluded.name, local_name = excluded.local_name, tagline = excluded.tagline, summary = excluded.summary, region_id = excluded.region_id, category = excluded.category, observed_by = excluded.observed_by, date_rule = excluded.date_rule, date_note = excluded.date_note, history = excluded.history, significance = excluded.significance, etiquette = excluded.etiquette, genres = excluded.genres, palette = excluded.palette, latitude = excluded.latitude, longitude = excluded.longitude, source_url = excluded.source_url, verification_status = excluded.verification_status;`,
  );
  const id = festivalId(f.slug);
  for (const code of f.countries) out.push(`insert into public.festival_countries (festival_id, country_id) values (${id}, ${countryId(code)}) on conflict do nothing;`);
  out.push(`delete from public.traditions where festival_id = ${id};`);
  f.traditions.forEach((body, i) => out.push(`insert into public.traditions (festival_id, kind, body, sort_order) values (${id}, 'tradition', ${q(body)}, ${i});`));
  f.regionalVariations.forEach((v, i) => out.push(`insert into public.traditions (festival_id, kind, place, body, sort_order) values (${id}, 'regional_variation', ${q(v.place)}, ${q(v.text)}, ${i});`));
  f.decor.forEach((body, i) => out.push(`insert into public.traditions (festival_id, kind, body, sort_order) values (${id}, 'decor', ${q(body)}, ${i});`));
  f.activities.forEach(([type, body], i) => out.push(`insert into public.traditions (festival_id, kind, activity_type, body, sort_order) values (${id}, 'activity', ${q(type)}, ${q(body)}, ${i});`));
  out.push(`delete from public.greetings where festival_id = ${id} and owner_id is null;`);
  for (const g of f.greetings) out.push(`insert into public.greetings (festival_id, body, language, meaning) values (${id}, ${q(g.text)}, ${q(g.language)}, ${q(g.meaning)});`);
  if (f.date.kind === "table") {
    for (const o of f.date.occurrences) {
      out.push(
        `insert into public.festival_dates (festival_id, starts_on, ends_on, status, note, source_url, last_checked_at) values (${id}, ${q(o.start)}, ${q(o.end)}, ${q(o.status)}, ${q(o.note)}, ${q(o.sources[0].url)}, ${o.lastChecked ? `${q(`${o.lastChecked}T00:00:00Z`)}::timestamptz` : "null"}) on conflict (festival_id, starts_on) do update set ends_on = excluded.ends_on, status = excluded.status, note = excluded.note, source_url = excluded.source_url, last_checked_at = excluded.last_checked_at;`,
      );
    }
  }
  out.push("");
}

for (const d of destinations) {
  out.push(
    `insert into public.destinations (slug, name, country_id, kind, summary, landmarks, experiences, itinerary, latitude, longitude, source_url) values (${q(d.slug)}, ${q(d.name)}, ${countryId(d.country)}, ${q(d.kind)}, ${q(d.summary)}, ${arr(d.landmarks)}, ${arr(d.experiences)}, ${arr(d.itinerary)}, ${d.lat}, ${d.lon}, ${q(d.source.url)}) on conflict (slug) do update set name = excluded.name, country_id = excluded.country_id, kind = excluded.kind, summary = excluded.summary, landmarks = excluded.landmarks, experiences = excluded.experiences, itinerary = excluded.itinerary, latitude = excluded.latitude, longitude = excluded.longitude, source_url = excluded.source_url;`,
  );
  for (const slug of d.festivals) out.push(`insert into public.festival_destinations (festival_id, destination_id) values (${festivalId(slug)}, (select id from public.destinations where slug = ${q(d.slug)})) on conflict do nothing;`);
}
out.push("");

for (const f of foods) {
  out.push(
    `insert into public.foods (slug, name, country_id, type, vegetarian, vegan, contains, ingredients, background, source_url) values (${q(f.slug)}, ${q(f.name)}, ${countryId(f.country)}, ${q(f.type)}, ${f.vegetarian}, ${f.vegan}, ${arr(f.contains)}, ${arr(f.ingredients)}, ${q(f.background)}, ${q(f.source.url)}) on conflict (slug) do update set name = excluded.name, country_id = excluded.country_id, type = excluded.type, vegetarian = excluded.vegetarian, vegan = excluded.vegan, contains = excluded.contains, ingredients = excluded.ingredients, background = excluded.background, source_url = excluded.source_url;`,
  );
  for (const slug of f.festivals) out.push(`insert into public.festival_foods (festival_id, food_id) values (${festivalId(slug)}, (select id from public.foods where slug = ${q(f.slug)})) on conflict do nothing;`);
}
out.push("");

for (const a of attire) {
  out.push(
    `insert into public.attire (slug, name, country_id, summary, textiles, craftsmanship, wearing, contemporary, source_url) values (${q(a.slug)}, ${q(a.name)}, ${countryId(a.country)}, ${q(a.summary)}, ${arr(a.textiles)}, ${q(a.craftsmanship)}, ${q(a.wearing)}, ${q(a.contemporary)}, ${q(a.source.url)}) on conflict (slug) do update set name = excluded.name, country_id = excluded.country_id, summary = excluded.summary, textiles = excluded.textiles, craftsmanship = excluded.craftsmanship, wearing = excluded.wearing, contemporary = excluded.contemporary, source_url = excluded.source_url;`,
  );
  for (const slug of a.festivals) out.push(`insert into public.festival_attire (festival_id, attire_id) values (${festivalId(slug)}, (select id from public.attire where slug = ${q(a.slug)})) on conflict do nothing;`);
}
out.push("");

for (const b of brands) {
  out.push(
    `insert into public.brands (slug, name, origin, tier, categories, about, known_for, official_url, is_partner, source_url) values (${q(b.slug)}, ${q(b.name)}, ${q(b.origin)}, ${q(b.tier)}, ${arr(b.categories)}, ${q(b.about)}, ${arr(b.knownFor)}, ${q(b.officialUrl)}, false, ${q(b.source.url)}) on conflict (slug) do update set name = excluded.name, origin = excluded.origin, tier = excluded.tier, categories = excluded.categories, about = excluded.about, known_for = excluded.known_for, official_url = excluded.official_url, source_url = excluded.source_url;`,
  );
}
out.push("-- Gift ideas are stored as curated example products: no prices, no stock, no ratings.");
for (const g of giftIdeas) {
  const brand = g.brands[0] ? `(select id from public.brands where slug = ${q(g.brands[0])})` : "null";
  out.push(
    `insert into public.products (slug, brand_id, title, category, tiers, recipients, interests, festival_slugs, note, is_curated_example) values (${q(g.slug)}, ${brand}, ${q(g.title)}, ${q(g.category)}, ${arr(g.tiers)}, ${arr(g.recipients)}, ${arr(g.interests)}, ${arr(g.festivals)}, ${q(g.note)}, true) on conflict (slug) do update set brand_id = excluded.brand_id, title = excluded.title, category = excluded.category, tiers = excluded.tiers, recipients = excluded.recipients, interests = excluded.interests, festival_slugs = excluded.festival_slugs, note = excluded.note;`,
  );
}
out.push("");

for (const a of artists) {
  out.push(
    `insert into public.artists (name, genre, country_name, languages, songs) values (${q(a.name)}, ${q(a.genre)}, ${q(a.country)}, ${arr(a.languages)}, ${arr(a.songs)}) on conflict (name) do update set genre = excluded.genre, country_name = excluded.country_name, languages = excluded.languages, songs = excluded.songs;`,
  );
}
for (const p of playlists) {
  out.push(`insert into public.playlists (slug, title, mood, owner_id, is_public) values (${q(p.slug)}, ${q(p.title)}, ${q(p.mood)}, null, true) on conflict (slug) do update set title = excluded.title, mood = excluded.mood;`);
  out.push(`delete from public.playlist_tracks where playlist_id = (select id from public.playlists where slug = ${q(p.slug)});`);
  p.tracks.forEach((t, i) =>
    out.push(`insert into public.playlist_tracks (playlist_id, artist_id, song, position) values ((select id from public.playlists where slug = ${q(p.slug)}), (select id from public.artists where name = ${q(t.artist)}), ${q(t.song)}, ${i});`),
  );
}
out.push("");

for (const a of ACTIVITY_LIBRARY) {
  out.push(
    `insert into public.activities (title, detail, type, audiences, interests, href) values (${q(a.title)}, ${q(a.detail)}, ${q(a.type)}, ${arr(a.audiences)}, ${arr(a.interests)}, ${q(a.href)}) on conflict (title) do update set detail = excluded.detail, type = excluded.type, audiences = excluded.audiences, interests = excluded.interests, href = excluded.href;`,
  );
}

out.push("", `-- Catalogue last reviewed ${DATES_CHECKED}.`, `update public.festival_dates set last_checked_at = coalesce(last_checked_at, ${checked}) where status <> 'unchecked';`, "commit;", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`Wrote supabase/seed.sql (${out.length} statements)`);
